import { geometry } from '../core/footprints';
import type { Problem } from '../core/problem';
import type { BoardSize, CutMode, Layout, Rotation } from '../core/types';

/**
 * - `paper`: the model of arXiv:2512.04910 lifted onto real footprints. Every net must lie on a
 *   single strip; pins 1 and 2 of a part may not share a strip; lexicographic objective
 *   total strip distance (TD) @3 > board area @2 > board width (strip span) @1.
 * - `relaxed`: nets may use several strips (the router joins them with links afterwards).
 *   Minimises (link weight × strips-per-net) + area, and forbids different nets in
 *   neighbouring holes when cuts must be made at a hole.
 */
export type AspMode = 'paper' | 'relaxed';

export interface Variant {
  rot: Rotation;
  span: number;
}

export interface AspEncoding {
  program: string;
  /** Per component, the rotation/span variants referenced by `place(C,V,X,Y)`. */
  variants: Variant[][];
  board: BoardSize;
  stats: { candidates: number; facts: number; bytes: number };
}

export interface AspOptions {
  mode: AspMode;
  board: BoardSize;
  cutMode: CutMode;
  /** Relaxed mode: cost of each extra strip a net occupies, relative to one hole of area. */
  linkWeight?: number;
}

// Footprint shapes are given once per variant (rotation + span) and candidate positions are
// generated by the grounder. This keeps the program text small, which matters because
// clingo-wasm passes it on the (limited) wasm stack.
const RULES_COMMON = `
% --- candidate positions: every variant at every on-board offset --------------------
hole(X,Y) :- board(BW,BH), X = 0..BW-1, Y = 0..BH-1.
cand(C,V,X,Y) :- variant(C,V,W,H), board(BW,BH), X = 0..BW-W, Y = 0..BH-H.

% --- choose exactly one placement per component ----------------------------------------
1 { place(C,V,X,Y) : cand(C,V,X,Y) } 1 :- comp(C).

% holes covered by each candidate (pins and body)
covers(C,V,X0,Y0,X0+DX,Y0+DY) :- cand(C,V,X0,Y0), vcell(C,V,DX,DY).
% hole exclusivity: at most one part per hole
:- hole(X,Y), 2 { place(C,V,X0,Y0) : covers(C,V,X0,Y0,X,Y) }.

% which net sits at which hole, and which strips each net uses
netat(N,X0+DX,Y0+DY) :- place(C,V,X0,Y0), vpinnet(C,V,N,DX,DY).
onstrip(N,Y) :- netat(N,_,Y).

% --- bounding box (paper: W = strip span, L = position span, A = W*L) -------------------
usedx(X0) :- place(C,V,X0,_).
usedx(X0+W-1) :- place(C,V,X0,_), variant(C,V,W,_).
usedy(Y0) :- place(C,V,_,Y0).
usedy(Y0+H-1) :- place(C,V,_,Y0), variant(C,V,_,H).
minx(M) :- M = #min { X : usedx(X) }.
maxx(M) :- M = #max { X : usedx(X) }.
miny(M) :- M = #min { Y : usedy(Y) }.
maxy(M) :- M = #max { Y : usedy(Y) }.
board_length(L) :- minx(A), maxx(B), L = B - A + 1.
board_width(W)  :- miny(A), maxy(B), W = B - A + 1.
board_area(A)   :- board_width(W), board_length(L), A = W * L.

#show place/4.
`;

const RULES_PAPER = `
% --- paper (arXiv:2512.04910) constraints ---------------------------------------------
% connectivity: all pins of a net on one strip
:- net(N), #count { Y : onstrip(N,Y) } > 1.
% no component shorts itself: pins 1 and 2 on different strips
:- place(C,V,_,_), vtd(C,V,0).

% --- paper objective: TD@3, area@2, width@1 ---------------------------------------------
strip_distance(C,D) :- place(C,V,_,_), vtd(C,V,D).
#minimize { D@3,C : strip_distance(C,D) }.
#minimize { A@2 : board_area(A) }.
#minimize { W@1 : board_width(W) }.
`;

const rulesRelaxed = (linkWeight: number, cutMode: CutMode) => `
% --- relaxed model: nets may span strips; links are added by the router afterwards --------
${
  cutMode === 'hole'
    ? `% a cut needs a free hole between pins of different nets on the same strip
:- netat(N1,X,Y), netat(N2,X+1,Y), N1 != N2.`
    : '% between-hole cuts: neighbouring pins of different nets are fine'
}
#minimize { ${linkWeight}@1,N,Y : onstrip(N,Y) }.
#minimize { A@1,area : board_area(A) }.
`;

export function encode(problem: Problem, opts: AspOptions): AspEncoding {
  const { board } = opts;
  const facts: string[] = [`board(${board.holes},${board.strips}).`];
  let candidates = 0;
  problem.nets.forEach((_, n) => facts.push(`net(${n}).`));
  const variants: Variant[][] = problem.netlist.components.map((_, ci) => {
    facts.push(`comp(${ci}).`);
    const fp = problem.fps[ci];
    const nets = problem.pinNets[ci];
    const vs: Variant[] = [];
    for (const rot of fp.rotations)
      for (const span of fp.spans) {
        const g = geometry(fp, rot, span);
        if (g.w > board.holes || g.h > board.strips) continue;
        const v = vs.length;
        vs.push({ rot, span });
        candidates += (board.holes - g.w + 1) * (board.strips - g.h + 1);
        facts.push(`variant(${ci},${v},${g.w},${g.h}).`);
        for (const h of [...g.pins, ...g.body]) facts.push(`vcell(${ci},${v},${h.x},${h.y}).`);
        g.pins.forEach((p, pi) => {
          if (nets[pi] >= 0) facts.push(`vpinnet(${ci},${v},${nets[pi]},${p.x},${p.y}).`);
        });
        if (g.pins.length >= 2) facts.push(`vtd(${ci},${v},${Math.abs(g.pins[0].y - g.pins[1].y)}).`);
      }
    return vs;
  });

  const header = [
    `% Stripboard placement — ${opts.mode === 'paper' ? 'paper model (arXiv:2512.04910)' : 'relaxed model (links added by router)'}`,
    `% Board: ${board.strips} strips x ${board.holes} holes. Components: ${problem.netlist.components.map((c, i) => `${i}=${c.ref}`).join(' ')}`,
    `% Nets: ${problem.nets.map((n, i) => `${i}=${n}`).join(' ')}`,
  ].join('\n');

  const rules =
    opts.mode === 'paper'
      ? RULES_COMMON + RULES_PAPER
      : RULES_COMMON + rulesRelaxed(Math.max(1, Math.round(opts.linkWeight ?? 6)), opts.cutMode);
  const program = `${header}\n\n${facts.join('\n')}\n${rules}`;
  return { program, variants, board, stats: { candidates, facts: facts.length, bytes: program.length } };
}

/** Turn a witness (list of atoms) back into a layout. */
export function decode(enc: AspEncoding, atoms: string[], nComponents: number): Layout | null {
  const layout: Layout = new Array(nComponents);
  let found = 0;
  for (const a of atoms) {
    const m = /^place\((\d+),(\d+),(\d+),(\d+)\)$/.exec(a);
    if (!m) continue;
    const c = Number(m[1]);
    const v = enc.variants[c]?.[Number(m[2])];
    if (!v) continue;
    if (!layout[c]) found++;
    layout[c] = { x: Number(m[3]), y: Number(m[4]), rot: v.rot, span: v.span };
  }
  return found === nComponents ? layout : null;
}

/**
 * Reasons the paper's one-strip-per-net model can never hold, found without solving:
 * a part whose same-net pins can't share a strip, or whose pins 1 and 2 can't be separated.
 */
export function paperModelObstacles(problem: Problem): string[] {
  const out: string[] = [];
  problem.netlist.components.forEach((c, ci) => {
    const fp = problem.fps[ci];
    const variants = fp.rotations.flatMap((rot) => fp.spans.map((span) => geometry(fp, rot, span)));
    for (let a = 0; a < c.pins.length; a++)
      for (let b = a + 1; b < c.pins.length; b++) {
        if (!c.pins[a] || c.pins[a] !== c.pins[b]) continue;
        if (!variants.some((g) => g.pins[a].y === g.pins[b].y)) {
          out.push(`${c.ref} pins ${a + 1} and ${b + 1} are both on ${c.pins[a]} but can never share a strip`);
        }
      }
    if (c.pins.length >= 2 && !variants.some((g) => g.pins[0].y !== g.pins[1].y)) {
      out.push(`${c.ref} pins 1 and 2 can never be on different strips`);
    }
    if (c.pins.length >= 2 && c.pins[0] && c.pins[0] === c.pins[1]) {
      out.push(`${c.ref} pins 1 and 2 share net ${c.pins[0]}, but the paper requires them on different strips`);
    }
  });
  return out;
}

/** A board just big enough around a layout's used area (plus margin), to keep grounding small. */
export function compactBoard(used: { width: number; height: number }, full: BoardSize, margin = 2): BoardSize {
  return {
    strips: Math.min(full.strips, used.height + margin),
    holes: Math.min(full.holes, used.width + margin),
  };
}
