import { geometry, placedGeometry } from '../core/footprints';
import type { Problem } from '../core/problem';
import type { BoardSize, CostWeights, Cut, CutMode, Layout, Link, Rotation } from '../core/types';

/**
 * - `paper`: the model of arXiv:2512.04910 lifted onto real footprints. Every net must lie on a
 *   single strip; pins 1 and 2 of a part may not share a strip; lexicographic objective
 *   total strip distance (TD) @3 > board area @2 > board width (strip span) @1.
 * - `relaxed`: nets may use several strips (the router joins them with links afterwards).
 *   Minimises (link weight × strips-per-net) + area, and forbids different nets in
 *   neighbouring holes when cuts must be made at a hole.
 * - `full`: goes beyond the paper. The solver also chooses every track cut and wire link,
 *   and electrical correctness is a reachability constraint (every pin of a net reached from
 *   one root pin through copper and links; no hole reached by two nets). Any answer is a
 *   complete, buildable layout. Minimises the same weighted cost as the annealer.
 */
export type AspMode = 'paper' | 'relaxed' | 'full';

export interface Variant {
  rot: Rotation;
  span: number;
}

export interface AspEncoding {
  program: string;
  /** Per component, the rotation/span variants referenced by `place(C,V,X,Y)`. */
  variants: Variant[][];
  board: BoardSize;
  stats: { candidates: number; facts: number; bytes: number };
}

export interface AspOptions {
  mode: AspMode;
  board: BoardSize;
  cutMode: CutMode;
  /** Relaxed mode: cost of each extra strip a net occupies, relative to one hole of area. */
  linkWeight?: number;
  /** Full mode: cost weights (scaled to integers internally). */
  weights?: CostWeights;
  /** Full mode: longest wire link, in strips. */
  maxLink?: number;
  /** Full mode: a known solution to steer the search towards (domain heuristics). */
  hint?: { layout: Layout; cuts: Cut[]; links: Link[] };
  /** Full mode: indices of components fixed at their `hint` placement (window search). */
  fixed?: number[];
  /**
   * Full mode with `hint`: only this rectangle (inclusive hole bounds) may change. Free parts
   * must stay inside it, and cuts and links outside it are fixed to the hint's.
   */
  region?: { x0: number; y0: number; x1: number; y1: number };
}

/** Integer scale applied to cost weights so fractional weights (e.g. 0.5) survive. */
export const FULL_WEIGHT_SCALE = 2;

// Footprint shapes are given once per variant (rotation + span) and candidate positions are
// generated by the grounder. This keeps the program text small, which matters because
// clingo-wasm passes it on the (limited) wasm stack.
const RULES_COMMON = `
% --- candidate positions: every variant at every on-board offset --------------------
hole(X,Y) :- board(BW,BH), X = 0..BW-1, Y = 0..BH-1.
cand(C,V,X,Y) :- variant(C,V,W,H), region(RX0,RY0,RX1,RY1), X = RX0..RX1-W+1, Y = RY0..RY1-H+1, not isfixed(C).
% parts held fixed (window search) have exactly one candidate
cand(C,V,X,Y) :- fixedpos(C,V,X,Y).
#defined isfixed/1.
#defined fixedpos/4.
inregion(X,Y) :- hole(X,Y), region(X0,Y0,X1,Y1), X0 <= X, X <= X1, Y0 <= Y, Y <= Y1.

% --- choose exactly one placement per component ----------------------------------------
1 { place(C,V,X,Y) : cand(C,V,X,Y) } 1 :- comp(C).

% holes covered by each candidate (pins and body)
covers(C,V,X0,Y0,X0+DX,Y0+DY) :- cand(C,V,X0,Y0), vcell(C,V,DX,DY).
% hole exclusivity: at most one part per hole
:- hole(X,Y), 2 { place(C,V,X0,Y0) : covers(C,V,X0,Y0,X,Y) }.

% which net sits at which hole, and which strips each net uses
netat(N,X0+DX,Y0+DY) :- place(C,V,X0,Y0), vpinnet(C,V,N,DX,DY).
onstrip(N,Y) :- netat(N,_,Y).

% --- bounding box (paper: W = strip span, L = position span, A = W*L) -------------------
usedx(X0) :- place(C,V,X0,_).
usedx(X0+W-1) :- place(C,V,X0,_), variant(C,V,W,_).
usedy(Y0) :- place(C,V,_,Y0).
usedy(Y0+H-1) :- place(C,V,_,Y0), variant(C,V,_,H).
minx(M) :- M = #min { X : usedx(X) }.
maxx(M) :- M = #max { X : usedx(X) }.
miny(M) :- M = #min { Y : usedy(Y) }.
maxy(M) :- M = #max { Y : usedy(Y) }.
board_length(L) :- minx(A), maxx(B), L = B - A + 1.
board_width(W)  :- miny(A), maxy(B), W = B - A + 1.
board_area(A)   :- board_width(W), board_length(L), A = W * L.

#show place/4.
`;

const RULES_PAPER = `
% --- paper (arXiv:2512.04910) constraints ---------------------------------------------
% connectivity: all pins of a net on one strip
:- net(N), #count { Y : onstrip(N,Y) } > 1.
% no component shorts itself: pins 1 and 2 on different strips
:- place(C,V,_,_), vtd(C,V,0).

% --- paper objective: TD@3, area@2, width@1 ---------------------------------------------
strip_distance(C,D) :- place(C,V,_,_), vtd(C,V,D).
#minimize { D@3,C : strip_distance(C,D) }.
#minimize { A@2 : board_area(A) }.
#minimize { W@1 : board_width(W) }.
`;

const rulesRelaxed = (linkWeight: number, cutMode: CutMode) => `
% --- relaxed model: nets may span strips; links are added by the router afterwards --------
${
  cutMode === 'hole'
    ? `% a cut needs a free hole between pins of different nets on the same strip
:- netat(N1,X,Y), netat(N2,X+1,Y), N1 != N2.`
    : '% between-hole cuts: neighbouring pins of different nets are fine'
}
#minimize { ${linkWeight}@1,N,Y : onstrip(N,Y) }.
#minimize { A@1,area : board_area(A) }.
`;

const rulesFull = (cutMode: CutMode, w: { cut: number; link: number; len: number; area: number }, anchored: boolean) => `
% ===== full model: placement + track cuts + wire links + electrical correctness =========
pinat(X0+DX,Y0+DY) :- place(C,V,X0,Y0), vpin(C,V,DX,DY).
occupied(X,Y) :- place(C,V,X0,Y0), covers(C,V,X0,Y0,X,Y).

% --- wire links: vertical, at most maxlink strips, never over pins, bodies or other links ---
lc(X,A,B) :- hole(X,A), hole(X,B), A < B, B - A <= maxlink, inregion(X,A), inregion(X,B).
lc(X,A,B) :- fixedlink(X,A,B).
{ link(X,A,B) : lc(X,A,B), not fixedlink(X,A,B) }.
link(X,A,B) :- fixedlink(X,A,B).
#defined fixedlink/3.
#defined fixedcut/2.
:- link(X,A,B), Y = A..B, occupied(X,Y).
:- hole(X,Y), 2 { link(X,A,B) : lc(X,A,B), A <= Y, Y <= B }.
linkend(X,A) :- link(X,A,_).
linkend(X,B) :- link(X,_,B).
used(X,Y) :- pinat(X,Y).
used(X,Y) :- linkend(X,Y).

% --- track cuts ----------------------------------------------------------------------
${
  cutMode === 'hole'
    ? `% a hole cut drills out hole X, isolating it
{ cut(X,Y) : inregion(X,Y), X > 0, X < BW-1, board(BW,_) }.
cut(X,Y) :- fixedcut(X,Y).
:- cut(X,Y), used(X,Y).
edge(X,Y) :- hole(X,Y), hole(X+1,Y), not cut(X,Y), not cut(X+1,Y).
% symmetry breaking: a cut can always slide left over empty holes, so require it to sit
% directly right of a used hole (canonical position)
:- cut(X,Y), not used(X-1,Y).`
    : `% a between-holes cut separates hole X from hole X+1
{ cut(X,Y) : inregion(X,Y), inregion(X+1,Y) }.
cut(X,Y) :- fixedcut(X,Y).
edge(X,Y) :- hole(X,Y), hole(X+1,Y), not cut(X,Y).
% symmetry breaking: slide cuts left until the hole on their left is used
:- cut(X,Y), not used(X,Y).`
}

% --- electrical correctness: reachability from one root pin per net ------------------
root(N,X0+DX,Y0+DY) :- place(C,V,X0,Y0), vroot(C,V,N,DX,DY).
reach(N,X,Y)   :- root(N,X,Y).
reach(N,X+1,Y) :- reach(N,X,Y), edge(X,Y).
reach(N,X,Y)   :- reach(N,X+1,Y), edge(X,Y).
reach(N,X,B)   :- reach(N,X,A), link(X,A,B).
reach(N,X,A)   :- reach(N,X,B), link(X,A,B).
% no opens: every pin of a net is reached from its root
:- netat(N,X,Y), not reach(N,X,Y).
% no shorts: no copper carries two nets
:- hole(X,Y), 2 { reach(N,X,Y) : net(N) }.
% links must join copper of the net they belong to (no dangling or useless links)
:- link(X,A,B), not reach(_,X,A).

% links count towards the used area
usedx(X) :- link(X,_,_).
usedy(A) :- link(_,A,_).
usedy(B) :- link(_,_,B).
${anchored ? `% symmetry breaking: translate the layout to the board's corner
:- minx(M), M > 0.
:- miny(M), M > 0.` : '% parts are fixed, so the layout is already anchored'}

% --- objective: the annealer's weighted cost (scaled to integers) ------------------------
#minimize { ${w.cut},cut,X,Y : cut(X,Y) }.
#minimize { ${w.link}+${w.len}*(B-A),link,X,A,B : link(X,A,B) }.
#minimize { ${w.area}*A,area : board_area(A) }.
#show cut/2.
#show link/3.
`;

/**
 * Put cuts in the canonical form the full model requires: slide each cut left over empty
 * holes until the hole on its left is used (a pin or a link end). Electrically identical;
 * cuts that slide off the strip end or onto another cut were redundant and are dropped.
 */
export function canonicalCuts(problem: Problem, layout: Layout, cuts: Cut[], links: Link[], cutMode: CutMode): Cut[] {
  const used = new Set<string>();
  layout.forEach((p, ci) => placedGeometry(problem.fps[ci], p).pins.forEach((h) => used.add(`${h.x},${h.y}`)));
  for (const l of links) used.add(`${l.x},${l.y1}`).add(`${l.x},${l.y2}`);
  const out = new Map<string, Cut>();
  for (const c of [...cuts].sort((a, b) => a.y - b.y || a.x - b.x)) {
    let x = c.x;
    if (cutMode === 'hole') {
      while (x - 1 >= 0 && !used.has(`${x - 1},${c.y}`) && !out.has(`${x - 1},${c.y}`)) x--;
      if (x === 0 || out.has(`${x - 1},${c.y}`)) continue;
    } else {
      while (x >= 0 && !used.has(`${x},${c.y}`)) x--;
      if (x < 0) continue;
    }
    out.set(`${x},${c.y}`, { ...c, x });
  }
  return [...out.values()];
}

/**
 * The inverse of `canonicalCuts`, for people: move each cut to the middle of the run of empty
 * holes it sits in, away from solder joints. Electrically identical.
 */
export function centreCuts(problem: Problem, layout: Layout, cuts: Cut[], links: Link[], cutMode: CutMode, holes: number): Cut[] {
  const used = new Set<string>();
  layout.forEach((p, ci) => placedGeometry(problem.fps[ci], p).pins.forEach((h) => used.add(`${h.x},${h.y}`)));
  for (const l of links) used.add(`${l.x},${l.y1}`).add(`${l.x},${l.y2}`);
  const taken = new Set(cuts.map((c) => `${c.x},${c.y}`));
  return cuts.map((c) => {
    // Free holes a cut may occupy (hole mode) or boundaries it may sit on (between mode).
    const free = (x: number) => x >= 0 && x < holes && !used.has(`${x},${c.y}`);
    let lo = c.x;
    let hi = c.x;
    if (cutMode === 'hole') {
      while (free(lo - 1) && !taken.has(`${lo - 1},${c.y}`)) lo--;
      while (free(hi + 1) && !taken.has(`${hi + 1},${c.y}`)) hi++;
    } else {
      // between x and x+1: may slide while the hole it passes over is empty
      while (lo - 1 >= 0 && free(lo)) lo--;
      while (hi + 1 < holes - 1 && free(hi + 1)) hi++;
    }
    const x = Math.floor((lo + hi) / 2);
    taken.delete(`${c.x},${c.y}`);
    taken.add(`${x},${c.y}`);
    return { ...c, x };
  });
}

/** Index of the footprint variant matching a placement's rotation and span, or -1. */
function variantIndex(vs: Variant[], p: { rot: Rotation; span: number }): number {
  return vs.findIndex((v) => v.rot === p.rot && v.span === p.span);
}

export function encode(problem: Problem, opts: AspOptions): AspEncoding {
  const { board } = opts;
  const facts: string[] = [`board(${board.holes},${board.strips}).`];
  let candidates = 0;
  problem.nets.forEach((_, n) => facts.push(`net(${n}).`));
  // Root pin per net: its first pin in netlist order.
  const rootOf = new Map<number, string>();
  problem.pinNets.forEach((nets, ci) =>
    nets.forEach((n, pi) => {
      if (n >= 0 && !rootOf.has(n)) rootOf.set(n, `${ci}.${pi}`);
    }),
  );
  const variants: Variant[][] = problem.netlist.components.map((_, ci) => {
    facts.push(`comp(${ci}).`);
    const fp = problem.fps[ci];
    const nets = problem.pinNets[ci];
    const vs: Variant[] = [];
    for (const rot of fp.rotations)
      for (const span of fp.spans) {
        const g = geometry(fp, rot, span);
        if (g.w > board.holes || g.h > board.strips) continue;
        const v = vs.length;
        vs.push({ rot, span });
        candidates += (board.holes - g.w + 1) * (board.strips - g.h + 1);
        facts.push(`variant(${ci},${v},${g.w},${g.h}).`);
        for (const h of [...g.pins, ...g.body]) facts.push(`vcell(${ci},${v},${h.x},${h.y}).`);
        g.pins.forEach((p, pi) => {
          if (nets[pi] >= 0) facts.push(`vpinnet(${ci},${v},${nets[pi]},${p.x},${p.y}).`);
          if (opts.mode === 'full') {
            facts.push(`vpin(${ci},${v},${p.x},${p.y}).`);
            if (nets[pi] >= 0 && rootOf.get(nets[pi]) === `${ci}.${pi}`) facts.push(`vroot(${ci},${v},${nets[pi]},${p.x},${p.y}).`);
          }
        });
        if (g.pins.length >= 2) facts.push(`vtd(${ci},${v},${Math.abs(g.pins[0].y - g.pins[1].y)}).`);
      }
    return vs;
  });

  const header = [
    `% Stripboard placement — ${opts.mode === 'paper' ? 'paper model (arXiv:2512.04910)' : 'relaxed model (links added by router)'}`,
    `% Board: ${board.strips} strips x ${board.holes} holes. Components: ${problem.netlist.components.map((c, i) => `${i}=${c.ref}`).join(' ')}`,
    `% Nets: ${problem.nets.map((n, i) => `${i}=${n}`).join(' ')}`,
  ].join('\n');

  const R = opts.mode === 'full' && opts.hint && opts.region ? opts.region : { x0: 0, y0: 0, x1: board.holes - 1, y1: board.strips - 1 };
  facts.push(`region(${R.x0},${R.y0},${R.x1},${R.y1}).`);
  const inR = (x: number, y: number) => x >= R.x0 && x <= R.x1 && y >= R.y0 && y <= R.y1;
  let extra = '';
  if (opts.mode === 'full') {
    const maxLink = Math.max(1, Math.min(board.strips - 1, opts.maxLink ?? 8));
    facts.push(`#const maxlink = ${maxLink}.`);
    const hint = opts.hint;
    const fixed = new Set(opts.fixed ?? []);
    if (hint) {
      // Domain heuristics: try the known solution first (needs --heuristic=Domain).
      hint.layout.forEach((p, ci) => {
        const v = variantIndex(variants[ci], p);
        if (v < 0) return;
        const atom = `place(${ci},${v},${p.x},${p.y})`;
        if (fixed.has(ci)) facts.push(`isfixed(${ci}).`, `fixedpos(${ci},${v},${p.x},${p.y}).`);
        else facts.push(`#heuristic ${atom}. [10,true]`);
      });
      const cuts = canonicalCuts(problem, hint.layout, hint.cuts, hint.links, opts.cutMode);
      for (const c of cuts) {
        const inside = inR(c.x, c.y) && (opts.cutMode === 'hole' || inR(c.x + 1, c.y));
        facts.push(inside ? `#heuristic cut(${c.x},${c.y}). [5,true]` : `fixedcut(${c.x},${c.y}).`);
      }
      for (const l of hint.links) {
        const a = Math.min(l.y1, l.y2);
        const b = Math.max(l.y1, l.y2);
        facts.push(inR(l.x, a) && inR(l.x, b) ? `#heuristic link(${l.x},${a},${b}). [5,true]` : `fixedlink(${l.x},${a},${b}).`);
      }
    }
    const w = opts.weights;
    const sc = (x: number | undefined, d: number) => Math.max(0, Math.round((x ?? d) * FULL_WEIGHT_SCALE));
    extra = rulesFull(opts.cutMode, { cut: sc(w?.cut, 2), link: sc(w?.link, 5), len: sc(w?.linkLength, 1), area: sc(w?.area, 1) }, fixed.size === 0);
  }
  const rules =
    opts.mode === 'paper'
      ? RULES_COMMON + RULES_PAPER
      : opts.mode === 'relaxed'
        ? RULES_COMMON + rulesRelaxed(Math.max(1, Math.round(opts.linkWeight ?? 6)), opts.cutMode)
        : RULES_COMMON + extra;
  const program = `${header}\n\n${facts.join('\n')}\n${rules}`;
  return { program, variants, board, stats: { candidates, facts: facts.length, bytes: program.length } };
}

/** Turn a witness (list of atoms) back into a layout. */
export function decode(enc: AspEncoding, atoms: string[], nComponents: number): Layout | null {
  const layout: Layout = new Array(nComponents);
  let found = 0;
  for (const a of atoms) {
    const m = /^place\((\d+),(\d+),(\d+),(\d+)\)$/.exec(a);
    if (!m) continue;
    const c = Number(m[1]);
    const v = enc.variants[c]?.[Number(m[2])];
    if (!v) continue;
    if (!layout[c]) found++;
    layout[c] = { x: Number(m[3]), y: Number(m[4]), rot: v.rot, span: v.span };
  }
  return found === nComponents ? layout : null;
}

/** Decode a full-model witness: placement plus the solver's own cuts and links. */
export function decodeFull(
  enc: AspEncoding,
  atoms: string[],
  nComponents: number,
  cutMode: CutMode,
): { layout: Layout; cuts: Cut[]; links: Link[] } | null {
  const layout = decode(enc, atoms, nComponents);
  if (!layout) return null;
  const cuts: Cut[] = [];
  const links: Link[] = [];
  for (const a of atoms) {
    let m = /^cut\((\d+),(\d+)\)$/.exec(a);
    if (m) {
      cuts.push({ x: Number(m[1]), y: Number(m[2]), kind: cutMode === 'hole' ? 'hole' : 'between' });
      continue;
    }
    m = /^link\((\d+),(\d+),(\d+)\)$/.exec(a);
    if (m) links.push({ net: '', x: Number(m[1]), y1: Number(m[2]), y2: Number(m[3]) });
  }
  cuts.sort((p, q) => p.y - q.y || p.x - q.x);
  links.sort((p, q) => p.x - q.x || p.y1 - q.y1);
  return { layout, cuts, links };
}

/**
 * Reasons the paper's one-strip-per-net model can never hold, found without solving:
 * a part whose same-net pins can't share a strip, or whose pins 1 and 2 can't be separated.
 */
export function paperModelObstacles(problem: Problem): string[] {
  const out: string[] = [];
  problem.netlist.components.forEach((c, ci) => {
    const fp = problem.fps[ci];
    const variants = fp.rotations.flatMap((rot) => fp.spans.map((span) => geometry(fp, rot, span)));
    for (let a = 0; a < c.pins.length; a++)
      for (let b = a + 1; b < c.pins.length; b++) {
        if (!c.pins[a] || c.pins[a] !== c.pins[b]) continue;
        if (!variants.some((g) => g.pins[a].y === g.pins[b].y)) {
          out.push(`${c.ref} pins ${a + 1} and ${b + 1} are both on ${c.pins[a]} but can never share a strip`);
        }
      }
    if (c.pins.length >= 2 && !variants.some((g) => g.pins[0].y !== g.pins[1].y)) {
      out.push(`${c.ref} pins 1 and 2 can never be on different strips`);
    }
    if (c.pins.length >= 2 && c.pins[0] && c.pins[0] === c.pins[1]) {
      out.push(`${c.ref} pins 1 and 2 share net ${c.pins[0]}, but the paper requires them on different strips`);
    }
  });
  return out;
}

/** A board just big enough around a layout's used area (plus margin), to keep grounding small. */
export function compactBoard(used: { width: number; height: number }, full: BoardSize, margin = 2): BoardSize {
  return {
    strips: Math.min(full.strips, used.height + margin),
    holes: Math.min(full.holes, used.width + margin),
  };
}
